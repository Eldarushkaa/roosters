export const errorKeys = Object.freeze(Object.fromEntries(
  Object.keys(messages.ru).filter((key) => key.startsWith('error.')).map((key) => [key.slice(6), key]),
));
const own = (object, key) => Object.prototype.hasOwnProperty.call(object, key);
const normalizeLanguage = (code) => languages.includes(code) ? code : 'ru';

/** Independent instances make locale/storage behavior testable without a DOM. */
export function createI18n(storage) {
  let language = 'ru';
  try { language = normalizeLanguage(storage?.getItem(LANGUAGE_STORAGE_KEY)); }
  catch { /* Embedded browsers may deny storage; keep the Russian default. */ }
  const locale = () => language === 'en' ? 'en-US' : 'ru-RU';
  const getLanguage = () => language;
  const setLanguage = (code) => {
    language = normalizeLanguage(code);
    try { storage?.setItem(LANGUAGE_STORAGE_KEY, language); }
    catch { /* The choice still lasts for this instance when storage is denied. */ }
    return language;
  };
  const has = (key) => typeof key === 'string' && own(messages.ru, key);
  const t = (key, params = {}) => {
    if (!has(key)) return String(key);
    const template = messages[language][key] ?? messages.ru[key];
    return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, name) => (
      params != null && own(params, name) ? String(params[name]) : match
    ));
  };
  const errorKey = (code) => typeof code === 'string' && own(errorKeys, code) ? errorKeys[code] : 'error.server';
  const numeric = (value) => Number.isFinite(Number(value)) ? Number(value) : 0;
  const formatNumber = (value) => new Intl.NumberFormat(locale()).format(numeric(value));
  const formatMoney = (minor) => new Intl.NumberFormat(locale(), { maximumFractionDigits: 2 }).format(numeric(minor) / 100);
  const formatDate = (timestamp) => {
    const value = Number(timestamp);
    if (!value || !Number.isFinite(value)) return t('common.later');
    const date = new Date(value * 1000);
    if (!Number.isFinite(date.getTime())) return t('common.later');
    return new Intl.DateTimeFormat(locale(), { hour: '2-digit', minute: '2-digit', day: 'numeric', month: 'short' }).format(date);
  };
  return Object.freeze({ getLanguage, setLanguage, t, has, locale, formatNumber, formatMoney, formatDate, errorKey });
}
